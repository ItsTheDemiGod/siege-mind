// Static baseline table for Director v2: the expected reward of each enemy type per wave, measured in STATIC games on the TRAIN seeds only
// (no Director code is involved, so the baseline cannot be circular). CLI: npm run baseline (writes src/data/directorBaseline.js).
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { config } from '../src/data/config.js';
import { ENEMY_ORDER } from '../src/data/enemies.js';
import { roundTo } from '../src/sim/telemetrySchema.js';
import { collectBaselineObservations, cellReward } from './diagnose.js';
import { PROTOCOL, protocolHash } from './protocol.js';
import { TRAIN_SEEDS } from './splits.js';

const r6 = (x) => roundTo(x, 6);
export const FALLBACK_MIN_WAVE = 5;

/**
 * Pure. Qualifying cells have units > 0 and a threat share (units * threatCost over the threat of the whole (seed, style, wave) group) of at least minThreatShare.
 * reward[type][w - 1] = threat-weighted mean reward over qualifying cells with wave in [w - window, w + window] within [1, waves] (null when there are none);
 * fallback[type] = the same pooled quantity over all qualifying cells with wave >= minWave (null when there are none).
 * @param {object[]} obs observations from collectBaselineObservations @param {{window: number, minThreatShare: number, minWave: number, waves: number}} o
 * @returns {{reward: Record<string, (number|null)[]>, fallback: Record<string, number|null>, cells: number}}
 */
export function buildBaseline(obs, { window, minThreatShare, minWave, waves }) {
  const totals = new Map();
  for (const o of obs) if (o.units > 0) { const k = `${o.seed}|${o.style}|${o.wave}`; totals.set(k, (totals.get(k) ?? 0) + o.units * o.threatCost); }
  const cells = [];
  for (const o of obs) {
    if (o.units <= 0) continue;
    const spent = o.units * o.threatCost;
    if (spent / totals.get(`${o.seed}|${o.style}|${o.wave}`) < minThreatShare) continue;
    cells.push({ type: o.type, wave: o.wave, spent, reward: cellReward(o) });
  }
  const pooled = (list) => { const w = list.reduce((a, c) => a + c.spent, 0); return w > 0 ? list.reduce((a, c) => a + c.spent * c.reward, 0) / w : null; };
  const reward = {};
  const fallback = {};
  for (const type of ENEMY_ORDER) {
    const own = cells.filter((c) => c.type === type);
    reward[type] = Array.from({ length: waves }, (_, i) => {
      const p = pooled(own.filter((c) => c.wave >= i + 1 - window && c.wave <= i + 1 + window));
      return p === null ? null : r6(p);
    });
    const f = pooled(own.filter((c) => c.wave >= minWave));
    fallback[type] = f === null ? null : r6(f);
  }
  return { reward, fallback, cells: cells.length };
}

/** @param {{reward: object, fallback: object, cells: number}} b @param {object} meta @returns {string} the source of src/data/directorBaseline.js */
export function baselineModuleSource(b, meta) {
  const arr = (a) => `Object.freeze([${a.map((x) => (x === null ? 'null' : String(x))).join(', ')}])`;
  const lines = [
    '// Static baseline reward per enemy type and wave for Director v2 (adaptive2).',
    `// Generated by: npm run baseline  (experiments/makeBaseline.js). Seeds ${meta.seeds[0]}-${meta.seeds.at(-1)} (the TRAIN split), styles ${meta.styles.join(', ')},`,
    `// bot knobs ${JSON.stringify(meta.knobs)}, ${meta.waves} waves, protocol hash ${meta.protocolHash}.`,
    '// Generated from STATIC games only, no Director code involved; regenerate with npm run baseline whenever the sim balance changes.',
    '// reward[type][w - 1] pools the cells of waves w - window .. w + window; null = no qualifying cell (the type was not yet unlocked).',
    'export const BASELINE_REWARD = Object.freeze({',
    ...ENEMY_ORDER.map((t) => `  ${t}: ${arr(b.reward[t])},`),
    '});',
    '',
    'export const BASELINE_FALLBACK = Object.freeze({',
    ...ENEMY_ORDER.map((t) => `  ${t}: ${b.fallback[t]},`),
    '});',
    '',
    `export const BASELINE_META = Object.freeze(${JSON.stringify(meta, null, 0).replace(/"([a-zA-Z]+)":/g, '$1: ').replace(/,/g, ', ')});`,
    '',
  ];
  return lines.join('\n');
}

function main() {
  const waves = PROTOCOL.waves;
  const params = { window: config.directorV2?.baselineWindow ?? 1, minThreatShare: config.director.minThreatShare, minWave: FALLBACK_MIN_WAVE, waves };
  console.log(`baseline: static mode, ${PROTOCOL.styles.length} styles x ${TRAIN_SEEDS.length} train seeds, ${waves} waves`);
  const obs = collectBaselineObservations({ seeds: [...TRAIN_SEEDS], styles: [...PROTOCOL.styles], waves, knobs: PROTOCOL.botKnobs });
  const b = buildBaseline(obs, params);
  const meta = { seeds: [...TRAIN_SEEDS], styles: [...PROTOCOL.styles], knobs: { ...PROTOCOL.botKnobs }, waves, window: params.window, minThreatShare: params.minThreatShare, minWave: params.minWave, qualifyingCells: b.cells, protocolHash: protocolHash() };
  const out = resolve(dirname(fileURLToPath(import.meta.url)), '../src/data/directorBaseline.js');
  writeFileSync(out, baselineModuleSource(b, meta));
  console.log(`wrote ${out} (${b.cells} qualifying cells)`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exit(main());
