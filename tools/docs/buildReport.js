// Generates docs/PROJECT_REPORT.md from the hand-written section files in docs/report/ and the results document: the core is pure (strings in, string out),
// only the CLI at the bottom reads and writes files. Deterministic: no clock, no random numbers.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join, resolve } from 'node:path';

export const RESULTS_SECTION = 6;
export const EMBEDDED_TITLES = Object.freeze(['Headline', 'Confirmatory results', 'Limits', 'What this does not show']);
const SECTION_FILE = /^(\d\d)-[a-z0-9-]+\.md$/;

/**
 * @param {string} md a markdown document @param {string} title the text of a second-level heading
 * @returns {string} the body of that section (after the heading line, up to the next second-level heading), without leading or trailing blank lines
 * @throws {Error} naming the heading when it is missing
 */
export function extractSection(md, title) {
  const lines = md.split('\n');
  const start = lines.findIndex((l) => l === `## ${title}`);
  if (start === -1) throw new Error(`docs/RESULTS.md has no section titled "${title}"; the report cannot embed it`);
  let end = lines.findIndex((l, i) => i > start && /^## /.test(l));
  if (end === -1) end = lines.length;
  return lines.slice(start + 1, end).join('\n').replace(/^\n+/, '').replace(/\s+$/, '');
}

/** @param {string} svg @returns {string} the text of the first <title> element, or '' */
export function svgTitle(svg) {
  const m = /<title[^>]*>([^<]+)<\/title>/.exec(svg);
  return m ? m[1].trim() : '';
}

/** GitHub-style anchor of a heading text. @param {string} text @returns {string} */
export function slug(text) {
  return text.toLowerCase().replace(/[^a-z0-9 -]/g, '').trim().replace(/ /g, '-');
}

/**
 * @param {{sections: {number: number, text: string}[], resultsMd: string, figures: {path: string, alt: string}[]}} input sections are the hand-written files (number from the file name)
 * @returns {string} the whole report
 */
export function buildReport({ sections, resultsMd, figures }) {
  const parts = sections.map((s) => {
    const m = /^## (.+)$/m.exec(s.text);
    if (!m || s.text.split('\n').findIndex((l) => l === m[0]) !== 0) throw new Error(`section ${s.number} must start with a second-level heading`);
    return { number: s.number, title: m[1], body: s.text.split('\n').slice(1).join('\n').replace(/^\n+/, '').replace(/\s+$/, '') };
  });
  parts.push({ number: RESULTS_SECTION, title: 'Results', body: resultsBody(resultsMd, figures) });
  parts.sort((a, b) => a.number - b.number);
  const numbers = parts.map((p) => p.number);
  if (new Set(numbers).size !== numbers.length) throw new Error(`duplicate section numbers: ${numbers.join(', ')}`);

  const head = (p) => `${p.number}. ${p.title}`;
  const out = [
    '# Siege Mind: project report',
    '',
    '*Generated by `tools/docs/buildReport.js` from `docs/report/*.md` and `docs/RESULTS.md`. Do not edit by hand; run `npm run report-doc`.*',
    '',
    '## Contents',
    '',
    ...parts.map((p) => `${p.number}. [${p.title}](#${slug(head(p))})`),
    '',
  ];
  for (const p of parts) out.push(`## ${head(p)}`, '', p.body, '');
  return `${out.join('\n').replace(/\n+$/, '')}\n`;
}

function resultsBody(resultsMd, figures) {
  const out = [
    'This section embeds, word for word, four sections of the generated results document ([RESULTS.md](RESULTS.md)); every number in this report comes from there.',
    '',
  ];
  for (const title of EMBEDDED_TITLES) out.push(`### ${title}`, '', extractSection(resultsMd, title), '');
  out.push('### Figures', '');
  for (const f of figures) out.push(`![${f.alt}](${f.path})`, '');
  out.push('The full results document, with the estimates, the contrast by wave, the per-pair tables, the replication check and the provenance of the held-out run, is [docs/RESULTS.md](RESULTS.md).');
  return out.join('\n');
}

/** @param {string[]} names file names of docs/report @returns {string[]} the hand-written section files in numeric order (06 is generated and must not exist) @throws {Error} on a gap or a stray file */
export function sectionFiles(names) {
  const files = names.filter((n) => n.endsWith('.md')).sort();
  const nums = files.map((f) => { const m = SECTION_FILE.exec(f); if (!m) throw new Error(`docs/report/${f} does not match NN-name.md`); return Number(m[1]); });
  const expected = [1, 2, 3, 4, 5, 7, 8, 9];
  if (nums.join() !== expected.join()) throw new Error(`docs/report must hold sections ${expected.join(', ')} (06 is generated); found ${nums.join(', ') || 'none'}`);
  return files;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = fileURLToPath(new URL('../../', import.meta.url));
  const dir = join(root, 'docs/report');
  const sections = sectionFiles(readdirSync(dir)).map((f) => ({ number: Number(f.slice(0, 2)), text: readFileSync(join(dir, f), 'utf8') }));
  const figDir = join(root, 'docs/results/figures-final');
  const figures = readdirSync(figDir).filter((f) => f.endsWith('.svg')).sort().map((f) => ({ path: `results/figures-final/${f}`, alt: svgTitle(readFileSync(join(figDir, f), 'utf8')) || f }));
  writeFileSync(join(root, 'docs/PROJECT_REPORT.md'), buildReport({ sections, resultsMd: readFileSync(join(root, 'docs/RESULTS.md'), 'utf8'), figures }));
  console.log(`docs/PROJECT_REPORT.md written (${sections.length + 1} sections, ${figures.length} figures)`);
}
