// Pure formatting of the audit results into docs/AUDIT.md (markdown) and a short text summary.
import { unnamedInteractive, badRoles, dialogProblems, duplicateIds, positiveTabindex, focusRingMissing, focusTrapEscapes, contrastProblems, overflowProblems, motionProblems } from './auditRules.js';

const f1 = (x) => x.toFixed(1);

/** Run every rule on one state's data. @param {object} state {name, snapshot, focus, traps, escapeCloses?} @returns {{name: string, findings: Record<string, any[]>, unresolved: number, checked: number}} */
export function evaluateState(state) {
  const c = contrastProblems(state.snapshot.contrast ?? []);
  const findings = {
    'Interactive elements without a name': unnamedInteractive(state.snapshot),
    'Roles without their state attribute': badRoles(state.snapshot),
    'Dialog problems': dialogProblems(state.snapshot),
    'Duplicate ids': duplicateIds(state.snapshot),
    'Positive tabindex': positiveTabindex(state.snapshot),
    'Focus without a visible ring': focusRingMissing(state.focus ?? []),
    'Focus escaped an open dialog': focusTrapEscapes(state.traps ?? []),
    'Text below the contrast minimum': c.failures,
    ...(state.escapeCloses === false ? { 'Escape did not close the dialog': [{ state: state.name }] } : {}),
  };
  return { name: state.name, findings, unresolved: c.unresolved.length, checked: c.checked };
}

const line = (x) => (typeof x !== 'object' ? `- ${x}` : `- ${Object.entries(x).map(([k, v]) => `${k}: ${typeof v === 'object' ? JSON.stringify(v) : v}`).join(', ')}`);

/** @param {{states: object[], sizes: object[], motion: object, perf: object[], meta: {generatedBy: string}}} r @returns {string} the markdown of docs/AUDIT.md */
export function auditMarkdown(r) {
  const out = ['# Accessibility and performance audit', '', `*Generated by ${r.meta.generatedBy}; do not edit by hand. The checks are a practical subset (names, roles, dialogs, ids, tab order, focus rings, focus traps, text contrast, overflow, reduced motion), not a full WCAG audit. Text contrast is computed from computed styles against the nearest opaque ancestor background; entries over the canvas are listed as unresolved, never as passes.*`, ''];
  for (const st of r.states) {
    const e = evaluateState(st);
    out.push(`## ${e.name}`, '');
    const bad = Object.entries(e.findings).filter(([, v]) => v.length > 0);
    if (bad.length === 0) out.push('none');
    for (const [k, v] of bad) { out.push(`**${k}** (${v.length})`, '', ...v.map(line), ''); }
    out.push('', `Contrast: ${e.checked} text entries checked, ${e.unresolved} unresolved.`, '');
  }
  out.push('## Window sizes', '');
  const ov = overflowProblems(r.sizes);
  out.push(ov.length ? ov.map(line).join('\n') : `none (${r.sizes.map((s) => s.label).join(', ')})`, '');
  out.push('## Reduced motion', '', `Normal motion: ${r.motion.normal.animations} running animations or transitions. With prefers-reduced-motion emulated: ${r.motion.reduced.animations}.`);
  const mp = motionProblems(r.motion.reduced);
  out.push(mp.length ? mp.map((m) => `- ${m}`).join('\n') : 'none', '');
  out.push('## Performance', '', 'Measured in headless Chrome without a GPU on this machine: an upper bound on frame time. Stress mode (40 towers, an enemy every 3 ticks), 3 s warm-up, 8 s sampled; the audio engine is unlocked.', '',
    '| Quality | Frames | Average ms | p95 ms | Max ms | Enemies alive |', '| --- | --- | --- | --- | --- | --- |',
    ...r.perf.map((p) => `| ${p.quality} | ${p.count} | ${f1(p.avgMs)} | ${f1(p.p95Ms)} | ${f1(p.maxMs)} | ${p.enemies} |`), '');
  return out.join('\n');
}

/** @returns {{violations: number, unresolved: number}} totals over all states, sizes and motion */
export function auditTotals(r) {
  let violations = 0;
  let unresolved = 0;
  for (const st of r.states) { const e = evaluateState(st); violations += Object.values(e.findings).reduce((n, v) => n + v.length, 0); unresolved += e.unresolved; }
  return { violations: violations + overflowProblems(r.sizes).length + motionProblems(r.motion.reduced).length, unresolved };
}
